// Regenerates ../cdr-toolkit/api/_pages.js from the HTML files in ./site
// Run after editing any page:   node build.js
const fs = require("fs");
const path = require("path");

const SITE = path.join(__dirname, "site");
const OUT = path.join(__dirname, "..", "cdr-toolkit", "api", "_pages.js");
const MIME = { ".png": "image/png", ".jpg": "image/jpeg", ".svg": "image/svg+xml" };

function walk(dir, base = "") {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(path.join(dir, d.name), base + d.name + "/") : [base + d.name]
  );
}

const pages = {};
for (const rel of walk(SITE)) {
  if (!rel.endsWith(".html")) continue;
  let html = fs.readFileSync(path.join(SITE, rel), "utf8");
  // images in site/assets are embedded into the page as data: URIs
  html = html.replace(/assets\/([\w.-]+)/g, (m, file) => {
    const ext = path.extname(file);
    return "data:" + MIME[ext] + ";base64," + fs.readFileSync(path.join(SITE, "assets", file)).toString("base64");
  });
  pages[rel] = html;
}
fs.writeFileSync(OUT, "// GENERATED by build.js - do not edit by hand\nmodule.exports = " + JSON.stringify(pages) + ";\n");
console.log("Wrote " + OUT + " (" + Object.keys(pages).length + " pages)");
